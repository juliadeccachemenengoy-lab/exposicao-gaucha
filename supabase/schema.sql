create table if not exists public.partidas (
  id bigint generated by default as identity primary key,
  partida_id text not null unique,
  jogo text not null check (jogo in ('personalidades', 'rota', 'bah-ou-nao-bah')),
  jogador text not null check (char_length(jogador) between 1 and 32),
  modo text not null default '',
  status text not null default 'iniciada' check (status in ('iniciada', 'concluida')),

  pontuacao integer not null default 0 check (pontuacao >= 0),
  acertos integer not null default 0 check (acertos >= 0),
  erros integer not null default 0 check (erros >= 0),
  duracao numeric(10,2) not null default 0 check (duracao >= 0),
  sequencia integer not null default 0 check (sequencia >= 0),
  respondidas integer not null default 0 check (respondidas >= 0),
  bonus integer not null default 0 check (bonus >= 0),

  dia_inicio date not null,
  dia_finalizacao date,
  iniciada_em timestamptz not null default now(),
  iniciada_em_cliente timestamptz,
  finalizada_em timestamptz,
  versao text not null default '',
  criado_em timestamptz not null default now(),
  atualizado_em timestamptz not null default now()
);

create index if not exists partidas_jogo_status_finalizada_idx
  on public.partidas (jogo, status, dia_finalizacao, pontuacao desc);
create index if not exists partidas_jogo_inicio_idx
  on public.partidas (jogo, dia_inicio);
create index if not exists partidas_finalizada_idx
  on public.partidas (finalizada_em desc);
create index if not exists partidas_jogador_idx
  on public.partidas (lower(jogador));

create or replace function public.set_atualizado_em()
returns trigger
language plpgsql
as $$
begin
  new.atualizado_em = now();
  return new;
end;
$$;

drop trigger if exists partidas_set_atualizado_em on public.partidas;
create trigger partidas_set_atualizado_em
before update on public.partidas
for each row execute function public.set_atualizado_em();

-- Os navegadores não acessam a tabela diretamente.
-- Somente as Netlify Functions usam a service role key no servidor.
alter table public.partidas enable row level security;
revoke all on table public.partidas from anon, authenticated;
grant all on table public.partidas to service_role;
grant usage, select on sequence public.partidas_id_seq to service_role;
